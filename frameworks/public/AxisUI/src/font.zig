//! Original, case-preserving ASCII 5-by-7 bitmap font and shared layout metrics.
const std = @import("std");
const Error = @import("surface.zig").Error;
pub const glyph_width: u32 = 5;
pub const glyph_height: u32 = 7;
pub const advance: u32 = 6;
pub const line_height: u32 = 10;
pub const offset_x: u32 = 0;
pub const offset_y: u32 = 1;
pub const Size = struct { width: u32 = 0, height: u32 = 0 };

/// Metrics are scaled in integer pixels. CR is ignored; tabs advance four cells.
/// Callers wrapping text or painting chrome use this same measurement contract.
pub fn measure(bytes: []const u8, scale: u8) Error!Size {
    if (scale == 0 or scale > 16) return error.InvalidScale;
    if (bytes.len == 0) return .{};
    var longest: u32 = 0;
    var columns: u32 = 0;
    var lines: u32 = 1;
    for (bytes) |byte| {
        if (byte == '\r') continue;
        if (byte == '\n') {
            longest = @max(longest, columns);
            columns = 0;
            lines = std.math.add(u32, lines, 1) catch return error.LayoutOverflow;
        } else columns = std.math.add(u32, columns, if (byte == '\t') 4 else 1) catch return error.LayoutOverflow;
    }
    longest = @max(longest, columns);
    return .{
        .width = std.math.mul(u32, longest, advance * scale) catch return error.LayoutOverflow,
        .height = std.math.mul(u32, lines, line_height * scale) catch return error.LayoutOverflow,
    };
}

